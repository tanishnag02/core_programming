class String2 {
    public static void main(String[] args) {

        // Creating string variables using String data type
        String greeting1 = "Hello";
        String greeting2 = "How are you?";

        // Printing the string variables to the console
        System.out.println(greeting1);     // Output: Hello
        System.out.println(greeting2);     // Output: How are you?
    }
}

